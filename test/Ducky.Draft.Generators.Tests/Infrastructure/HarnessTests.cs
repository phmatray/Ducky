using Microsoft.CodeAnalysis;

namespace Ducky.Draft.Generators.Tests.Infrastructure;

// Self-tests of the Draft generator harness: a helper that silently passes would hollow out every generator test built on it.
public sealed class HarnessTests
{
    private const string Consumer = """
        namespace App;

        /// <summary>A todo item.</summary>
        /// <param name="Title">The title.</param>
        [Ducky.Draft.Draftable]
        public sealed partial record Todo(string Title);
        """;

    [Fact]
    public void Harness_RealDuckyDraftConsumer_CompilesClean() =>
        GeneratorHarness.Compile(Consumer).ShouldCompileClean();

    [Fact]
    public void Harness_StrictConsumerSettings_ReportDocsAndNullability()
    {
        var compilation = GeneratorHarness.Compile("public class C { public string S = null; }");

        Should.Throw<ShouldAssertException>(compilation.ShouldCompileClean).Message.ShouldSatisfyAllConditions(
            m => m.ShouldContain("CS1591"),
            m => m.ShouldContain("CS8625"));
    }

    [Fact]
    public Task Harness_DraftGenerator_Snapshot()
    {
        var driver = GeneratorHarness.Run(new DraftGenerator(), GeneratorHarness.Compile(Consumer), out var output);

        output.ShouldCompileClean();
        return GeneratorHarness.VerifyRun(driver);
    }

    // The planted warnings: an undocumented public type (CS1591 only under DocumentationMode.Diagnose) with a lower-case
    // name (CS8981 only at warning level >= 7). Warnings, not errors: the zero-diagnostics helper fails on them, so
    // generated trees get the strict parse options and compilation settings, and the snapshot carries the generated source.
    private const string PlantedWarning = """
        // <auto-generated/>
        #nullable enable
        public class c { }
        """;

    [Fact]
    public Task Harness_PlantedWarningInGeneratedCompilation_FailsZeroDiagnostics()
    {
        var driver = GeneratorHarness.Run(new ProbeGenerator(keepSymbol: false, PlantedWarning), GeneratorHarness.Compile(Consumer), out var output);

        output.GetDiagnostics(TestContext.Current.CancellationToken).ShouldAllBe(d => d.Severity != DiagnosticSeverity.Error);
        Should.Throw<ShouldAssertException>(output.ShouldCompileClean).Message.ShouldSatisfyAllConditions(
            m => m.ShouldContain("CS1591"),
            m => m.ShouldContain("CS8981"));
        return GeneratorHarness.VerifyRun(driver);
    }

    // A crashing generator (CS8785) leaves its output out of the compilation, and a diagnostic it reports never reaches
    // the output compilation: Run fails on both, or a crashing shape would compile "clean".
    [Fact]
    public void Harness_GeneratorThrows_RunFails() =>
        Should.Throw<ShouldAssertException>(() => GeneratorHarness.Run(
            new ProbeGenerator(keepSymbol: false, output: ProbeOutput.Throw), GeneratorHarness.Compile(Consumer), out _));

    [Fact]
    public void Harness_GeneratorReportsDiagnostic_RunFails() =>
        Should.Throw<ShouldAssertException>(() => GeneratorHarness.Run(
            new ProbeGenerator(keepSymbol: false, output: ProbeOutput.Report), GeneratorHarness.Compile(Consumer), out _))
            .Message.ShouldContain("PROBE001");

    [Fact]
    public void Harness_EquatableModel_Cached() =>
        GeneratorHarness.ShouldCacheSteps(new ProbeGenerator(keepSymbol: false), GeneratorHarness.Compile(Consumer), ProbeGenerator.Step);

    [Fact]
    public void Harness_SymbolModelOrUnknownStep_NotCached()
    {
        Should.Throw<ShouldAssertException>(() => GeneratorHarness.ShouldCacheSteps(
            new ProbeGenerator(keepSymbol: true), GeneratorHarness.Compile(Consumer), ProbeGenerator.Step));
        Should.Throw<ShouldAssertException>(() => GeneratorHarness.ShouldCacheSteps(
            new ProbeGenerator(keepSymbol: false), GeneratorHarness.Compile(Consumer), "Unknown"));
    }

    private enum ProbeOutput { None, Throw, Report }

    // One tracked step over [Draftable] types: the type name (equatable) or the symbol itself (never cached); emits
    // `emit` (when set) once per model, or throws or reports PROBE001 there.
    private sealed class ProbeGenerator(bool keepSymbol, string? emit = null, ProbeOutput output = ProbeOutput.None) : IIncrementalGenerator
    {
        public const string Step = "Model";

#pragma warning disable RS2008 // justification: a test-only probe descriptor, never shipped in an analyzer release
        private static readonly DiagnosticDescriptor _probe = new("PROBE001", "Probe", "Probe diagnostic", "Probe", DiagnosticSeverity.Warning, true);
#pragma warning restore RS2008

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var models = context.SyntaxProvider
                .ForAttributeWithMetadataName("Ducky.Draft.DraftableAttribute", (_, _) => true,
                    (c, _) => keepSymbol ? c.TargetSymbol : (object)c.TargetSymbol.Name)
                .WithTrackingName(Step);
            context.RegisterSourceOutput(models, (spc, _) =>
            {
                if (emit is not null)
                {
                    spc.AddSource("Probe.g.cs", emit);
                }
                if (output == ProbeOutput.Throw)
                {
                    throw new InvalidOperationException("probe");
                }
                if (output == ProbeOutput.Report)
                {
                    spc.ReportDiagnostic(Diagnostic.Create(_probe, Location.None));
                }
            });
        }
    }
}
