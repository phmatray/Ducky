using System.Collections.Immutable;
using Ducky.Shared.Generators;

namespace Ducky.Generators.Tests;

// The shared generator helpers of src/Shared.Generators, linked into Ducky.Generators (SPEC §16.1).
public sealed class SharedHelpersTests
{
    // GEN-02 {Asm}: invalid identifier characters become `_`; a leading digit or a reserved keyword gets a `_` prefix;
    // null becomes Anonymous. Names differing only in such characters collide (documented, not hashed).
    [Theory]
    [InlineData(null, "Anonymous")]
    [InlineData("", "Anonymous")]
    [InlineData("App", "App")]
    [InlineData("_App", "_App")]
    [InlineData("MyCompany.Todos", "MyCompany_Todos")]
    [InlineData("My.App", "My_App")]
    [InlineData("My-App", "My_App")]
    [InlineData("My_App", "My_App")]
    [InlineData("My App+1", "My_App_1")]
    [InlineData("1App", "_1App")]
    [InlineData("1.0", "_1_0")]
    [InlineData("class", "_class")]
    [InlineData("Class", "Class")]
    [InlineData("var", "var")]
    [InlineData("@class", "_class")]
    [InlineData("Écoles.Ünïcode", "Écoles_Ünïcode")]
    [InlineData("é", "é")]
    [InlineData("́e", "_́e")]
    public void AssemblyNameSanitizer_Table(string? assemblyName, string expected) =>
        AssemblyNameSanitizer.Sanitize(assemblyName).ShouldBe(expected);

    // Parameter names keep their case and escape reserved keywords with `@`; hint names keep only [A-Za-z0-9_.].
    [Theory]
    [InlineData("By", "By", "By")]
    [InlineData("class", "@class", "class")]
    [InlineData("Class", "Class", "Class")]
    [InlineData("var", "var", "var")]
    [InlineData("N.Outer+Inner", "N.Outer+Inner", "N.Outer_Inner")] // collides with N.Outer_Inner: callers deduplicate
    [InlineData("N.List`1", "N.List`1", "N.List_1")]
    [InlineData("@class", "@class", "_class")]
    [InlineData("<>c__Display", "<>c__Display", "__c__Display")]
    [InlineData("azAZ09_.", "azAZ09_.", "azAZ09_.")]
    [InlineData("`{@[/:", "`{@[/:", "______")]
    [InlineData("Écoles", "Écoles", "_coles")]
    public void IdentifierSanitizer_Table(string input, string escaped, string hintName)
    {
        IdentifierSanitizer.EscapeKeyword(input).ShouldBe(escaped);
        IdentifierSanitizer.HintName(input).ShouldBe(hintName);
    }

    private sealed record Model(string Name, EquatableArray<string> Members);

    [Fact]
    public void EquatableArray_ValueEquality()
    {
        var ab = new EquatableArray<string>(["a", "b"]);
        var ab2 = new EquatableArray<string>([.. "ab".Select(c => c.ToString())]);
        var empty = new EquatableArray<string>([]);

        ab.Equals(ab2).ShouldBeTrue();
        ab.Equals((object)ab2).ShouldBeTrue();
        ab.GetHashCode().ShouldBe(ab2.GetHashCode());
        new Model("M", ab).ShouldBe(new Model("M", ab2));

        ab.Equals(new EquatableArray<string>(["b", "a"])).ShouldBeFalse();
        ab.Equals(new EquatableArray<string>(["a"])).ShouldBeFalse();
        ab.Equals(empty).ShouldBeFalse();
        ab.Equals((object)ImmutableArray.Create("a", "b")).ShouldBeFalse();
        ab.Equals(null).ShouldBeFalse();

        // default (a model field never assigned, or a default ImmutableArray) reads as empty.
        foreach (var unset in new[] { default, new EquatableArray<string>(default) })
        {
            unset.Items.ShouldBeEmpty();
            unset.Equals(empty).ShouldBeTrue();
            unset.GetHashCode().ShouldBe(empty.GetHashCode());
        }
        ab.Items.ShouldBe(["a", "b"]);
    }

    [Fact]
    public void CodeWriter_RawTemplates_IndentedUnderPrologue()
    {
        var writer = new CodeWriter()
            .Line("namespace N;")
            .Line()
            .Open("public static class C")
            .Line("""
                /// <summary>M.</summary>
                public static void M()
                {
                }
                """)
            .Open("private static class Nested")
            .Line("int a;\r\n\r\nint b;")
            .Close()
            .Close();

        writer.ToString().ShouldBe("""
            // <auto-generated/>
            #nullable enable

            namespace N;

            public static class C
            {
                /// <summary>M.</summary>
                public static void M()
                {
                }
                private static class Nested
                {
                    int a;

                    int b;
                }
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal));
    }
}
