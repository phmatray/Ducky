using Ducky.Generators.Tests.Infrastructure;
using Microsoft.CodeAnalysis;

namespace Ducky.Generators.Tests.Registration;

// ADR-0051 (#313): a partial Slice<TState, TAction> over a union gets a RegisterCases override with one On<Case> per case,
// read as ADR-0050 says; a non-union action type is DUCKY026, a non-partial slice DUCKY027, a case dispatch never matches
// DUCKY029, a file-local slice DUCKY030 and a hand-written RegisterCases DUCKY031 (#324), with no override emitted.
public sealed class UnionSliceTests
{
    private const string Cart = """
        #pragma warning disable CS1591 // justification: undocumented test sources
        namespace App;
        public sealed record Cart(int Count);
        public sealed record AddItem(int Count);
        public sealed record RemoveItem(int Count);
        public sealed record Clear;
        public union CartAction(AddItem, RemoveItem, Clear);

        """;

    private const string Reduce = """
            protected override Cart Initial => new(0);
            protected override Cart Reduce(Cart state, CartAction action) => action switch
            {
                AddItem a => new(state.Count + a.Count),
                RemoveItem r => new(state.Count - r.Count),
                Clear => new(0),
            };
        """;

    [Fact]
    public void UnionSlice_RegistersEachCase_AndCompilesClean()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            public sealed partial class CartSlice : Ducky.Slice<Cart, CartAction>
            {
            {{Reduce}}
            }
            """), out var output);

        output.ShouldCompileClean();
        Generated(output, "App.CartSlice.UnionSlice.g.cs").ShouldBe("""
            // <auto-generated/>
            #nullable enable

            namespace App;

            partial class CartSlice
            {
                /// <inheritdoc />
                protected override void RegisterCases()
                {
                    #pragma warning disable CS0612, CS0618 // justification: generated code references user [Obsolete] cases (GEN-06)
                    On<global::App.AddItem>((s, a) => Reduce(s, new global::App.CartAction(a)));
                    On<global::App.RemoveItem>((s, a) => Reduce(s, new global::App.CartAction(a)));
                    On<global::App.Clear>((s, a) => Reduce(s, new global::App.CartAction(a)));
                    #pragma warning restore CS0612, CS0618
                }
            }

            """, StringCompareShould.IgnoreLineEndings);
    }

    // A nested union's cases are registered through both wrappers, the first path to a case wins, and a nested, generic
    // slice in the global namespace is re-declared with its containing types.
    [Fact]
    public void UnionSlice_NestedUnionGenericAndContainingTypes_CompilesClean()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile("""
            #pragma warning disable CS1591 // justification: undocumented test sources
            public sealed record Cart(int Count);
            public sealed record Add(int Count);
            public sealed record Other;
            public union Inner(Add, Other);
            public union Outer(Inner, Add);
            public static partial class Holder
            {
                public partial interface IBox
                {
                    public partial record struct Box
                    {
                        public abstract partial class @class<T> : Ducky.Slice<Cart, Outer>
                        {
                            protected override Cart Initial => new(0);
                            protected override Cart Reduce(Cart state, Outer action) => state;
                        }
                    }
                }
            }
            """), out var output);

        output.ShouldCompileClean();
        var generated = Generated(output, "Holder.IBox.Box._class_T_.UnionSlice.g.cs");
        generated.ShouldContain("partial class Holder\n");
        generated.ShouldContain("partial interface IBox\n");
        generated.ShouldContain("partial record struct Box\n");
        generated.ShouldContain("partial class @class<T>\n");
        generated.ShouldContain("On<global::Add>((s, a) => Reduce(s, new global::Outer(new global::Inner(a))));");
        generated.ShouldContain("On<global::Other>((s, a) => Reduce(s, new global::Outer(new global::Inner(a))));");
        generated.ShouldNotContain("new global::Outer(a)");
    }

    // ADR-0050: a union from a referenced assembly presents its cases the same way.
    [Fact]
    public void UnionSlice_ReferencedUnion_RegistersEachCase()
    {
        var actions = GeneratorHarness.Compile(Cart).WithAssemblyName("Actions");
        actions.ShouldCompileClean();
