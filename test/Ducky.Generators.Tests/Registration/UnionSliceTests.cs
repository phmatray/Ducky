    // One diagnostic, no override emitted, and the output still compiles (the slice merely registers nothing).
    private static Diagnostic Diagnose(string source, out Compilation output)
    {
        var input = GeneratorHarness.Compile(source);
        DiagnosingHarness.Run(new RegistrationGenerator(), input, out output, out var diagnostics);
        output.ShouldCompileClean();
        output.SyntaxTrees.ShouldNotContain(t => t.FilePath.EndsWith(".UnionSlice.g.cs", StringComparison.Ordinal));
        return diagnostics.ShouldHaveSingleItem();
    }

    private static string Generated(Compilation output, string hintName) =>
        output.SyntaxTrees.Single(t => t.FilePath.EndsWith(hintName, StringComparison.Ordinal)).ToString();

    private static void ShouldBeAt(Diagnostic diagnostic, Compilation compilation, string typeName)
    {
        var declared = compilation.GetSymbolsWithName(typeName, SymbolFilter.Type, TestContext.Current.CancellationToken).Single().Locations[0];
        diagnostic.Location.SourceTree.ShouldBe(declared.SourceTree);
        diagnostic.Location.SourceSpan.ShouldBe(declared.SourceSpan);
    }
