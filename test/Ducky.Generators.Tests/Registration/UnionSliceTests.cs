    [Theory]
    [InlineData("public sealed partial class CartSlice", "protected override void RegisterCases() => On<AddItem>((s, a) => s);")]
    [InlineData("public sealed class CartSlice", "protected override void RegisterCases() => On<AddItem>((s, a) => s);")]
