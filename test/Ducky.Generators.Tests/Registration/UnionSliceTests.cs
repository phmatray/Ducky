using Ducky.Generators.Tests.Infrastructure;
using Microsoft.CodeAnalysis;

namespace Ducky.Generators.Tests.Registration;

// ADR-0051 (#313): a partial Slice<TState, TAction> over a union gets a RegisterCases override with one On<Case> per case,
// read as ADR-0050 says; a non-union action type is DUCKY026 and a non-partial slice DUCKY027, with no override emitted.
public sealed class UnionSliceTests
{
    private const string Cart = """
        #pragma warning disable CS1591 // justification: undocumented test sources
        namespace App;
        public sealed record Cart(int Count);
        public sealed record AddItem(int Count);
        public sealed record RemoveItem(int Count);
        public sealed record Clear;
        public union CartAction(AddItem, RemoveItem, Clear);

        """;

    private const string Reduce = """
            protected override Cart Initial => new(0);
            protected override Cart Reduce(Cart state, CartAction action) => action switch
            {
                AddItem a => new(state.Count + a.Count),
                RemoveItem r => new(state.Count - r.Count),
                Clear => new(0),
            };
        """;

    [Fact]
    public void UnionSlice_RegistersEachCase_AndCompilesClean()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            public sealed partial class CartSlice : Ducky.Slice<Cart, CartAction>
            {
            {{Reduce}}
            }
            """), out var output);

        output.ShouldCompileClean();
        Generated(output, "App.CartSlice.UnionSlice.g.cs").ShouldBe("""
            // <auto-generated/>
            #nullable enable

            namespace App;

            partial class CartSlice
            {
                /// <inheritdoc />
                protected override void RegisterCases()
                {
                    On<global::App.AddItem>((s, a) => Reduce(s, new global::App.CartAction(a)));
                    On<global::App.RemoveItem>((s, a) => Reduce(s, new global::App.CartAction(a)));
                    On<global::App.Clear>((s, a) => Reduce(s, new global::App.CartAction(a)));
                }
            }

            """, StringCompareShould.IgnoreLineEndings);
    }

    // A nested union's cases are registered through both wrappers, the first path to a case wins, and a nested, generic
    // slice in the global namespace is re-declared with its containing types.
    [Fact]
    public void UnionSlice_NestedUnionGenericAndContainingTypes_CompilesClean()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile("""
            #pragma warning disable CS1591 // justification: undocumented test sources
            public sealed record Cart(int Count);
            public sealed record Add(int Count);
            public sealed record Other;
            public union Inner(Add, Other);
            public union Outer(Inner, Add);
            public static partial class Holder
            {
                public partial record struct Box
                {
                    public abstract partial class @class<T> : Ducky.Slice<Cart, Outer>
                    {
                        protected override Cart Initial => new(0);
                        protected override Cart Reduce(Cart state, Outer action) => state;
                    }
                }
            }
            """), out var output);

        output.ShouldCompileClean();
        var generated = Generated(output, "Holder.Box._class_T_.UnionSlice.g.cs");
        generated.ShouldContain("partial class Holder\n");
        generated.ShouldContain("partial record struct Box\n");
        generated.ShouldContain("partial class @class<T>\n");
        generated.ShouldContain("On<global::Add>((s, a) => Reduce(s, new global::Outer(new global::Inner(a))));");
        generated.ShouldContain("On<global::Other>((s, a) => Reduce(s, new global::Outer(new global::Inner(a))));");
        generated.ShouldNotContain("new global::Outer(a)");
    }

    // ADR-0050: a union from a referenced assembly presents its cases the same way.
    [Fact]
    public void UnionSlice_ReferencedUnion_RegistersEachCase()
    {
        var actions = GeneratorHarness.Compile(Cart).WithAssemblyName("Actions");
        actions.ShouldCompileClean();
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile($$"""
            #pragma warning disable CS1591 // justification: undocumented test sources
            namespace App;
            public sealed partial class CartSlice : Ducky.Slice<Cart, CartAction>
            {
            {{Reduce}}
            }
            """).AddReferences(actions.ToMetadataReference()), out var output);

        output.ShouldCompileClean();
        var generated = Generated(output, "App.CartSlice.UnionSlice.g.cs");
        generated.ShouldContain("On<global::App.AddItem>");
        generated.ShouldContain("On<global::App.RemoveItem>");
        generated.ShouldContain("On<global::App.Clear>");
    }

    // A slice deriving from a union slice inherits its override; only the direct derivation is generated.
    [Fact]
    public void UnionSlice_DerivedFromAUnionSlice_IsNotGenerated()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            public abstract partial class CartBase : Ducky.Slice<Cart, CartAction>
            {
            {{Reduce}}
            }
            public sealed class CartSlice : CartBase { }
            """), out var output);

        output.ShouldCompileClean();
        output.SyntaxTrees.Count(t => t.FilePath.EndsWith(".UnionSlice.g.cs", StringComparison.Ordinal)).ShouldBe(1);
    }

    // Acceptance 2: a case the union gains is registered, and Reduce's switch no longer covers it.
    [Fact]
    public void UnionSlice_UnhandledCase_IsNonExhaustive()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart.Replace("Clear);", "Clear, Checkout);", StringComparison.Ordinal) + $$"""
            public sealed record Checkout;
            public sealed partial class CartSlice : Ducky.Slice<Cart, CartAction>
            {
            {{Reduce}}
            }
            """), out var output);

        Generated(output, "App.CartSlice.UnionSlice.g.cs").ShouldContain("On<global::App.Checkout>");
        output.GetDiagnostics(TestContext.Current.CancellationToken).Select(d => d.Id).ShouldBe(["CS8509"]);
    }

    [Fact]
    public void UnionSlice_NonUnionAction_IsDucky026()
    {
        var diagnostic = Diagnose(Cart + """
            public sealed partial class CartSlice : Ducky.Slice<Cart, AddItem>
            {
                protected override Cart Initial => new(0);
                protected override Cart Reduce(Cart state, AddItem action) => state;
            }
            """, out var output);

        diagnostic.Id.ShouldBe("DUCKY026");
        diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture)
            .ShouldBe("'App.CartSlice' derives from Slice<TState, TAction>, but its action type 'App.AddItem' is not a C# union");
        ShouldBeAt(diagnostic, output, "CartSlice");
    }

    [Theory]
    [InlineData("public sealed class CartSlice", "", "'App.CartSlice'")]
    [InlineData("public sealed partial class CartSlice", "public static class Holder {", "'App.Holder'")]
    [InlineData("public sealed class CartSlice", "public static class Holder {", "'App.Holder', 'App.Holder.CartSlice'")]
    public void UnionSlice_NotPartial_IsDucky027(string declaration, string container, string types)
    {
        var diagnostic = Diagnose(Cart + container + $$"""
            {{declaration}} : Ducky.Slice<Cart, CartAction>
            {
            {{Reduce}}
            }
            """ + (container.Length > 0 ? "}" : ""), out var output);

        diagnostic.Id.ShouldBe("DUCKY027");
        var display = container.Length > 0 ? "App.Holder.CartSlice" : "App.CartSlice";
        diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture).ShouldBe($"The cases of '{display}' can't be registered: declare {types} partial");
        ShouldBeAt(diagnostic, output, "CartSlice");
    }

    [Fact]
    public void Caching_RegistrationUnionSlices_Cached() =>
        GeneratorHarness.ShouldCacheSteps(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            public sealed partial class CartSlice : Ducky.Slice<Cart, CartAction>
            {
            {{Reduce}}
            }
            """), "RegistrationUnionSlices", "RegistrationUnionEmit");

    // One diagnostic, no override emitted, and the output still compiles (the slice merely registers nothing).
    private static Diagnostic Diagnose(string source, out Compilation output)
    {
        var input = GeneratorHarness.Compile(source);
        DiagnosingHarness.Run(new RegistrationGenerator(), input, out output, out var diagnostics);
        output.ShouldCompileClean();
        output.SyntaxTrees.ShouldNotContain(t => t.FilePath.EndsWith(".UnionSlice.g.cs", StringComparison.Ordinal));
        return diagnostics.ShouldHaveSingleItem();
    }

    private static string Generated(Compilation output, string hintName) =>
        output.SyntaxTrees.Single(t => t.FilePath.EndsWith(hintName, StringComparison.Ordinal)).ToString();

    private static void ShouldBeAt(Diagnostic diagnostic, Compilation compilation, string typeName)
    {
        var declared = compilation.GetSymbolsWithName(typeName, SymbolFilter.Type, TestContext.Current.CancellationToken).Single().Locations[0];
        diagnostic.Location.SourceTree.ShouldBe(declared.SourceTree);
        diagnostic.Location.SourceSpan.ShouldBe(declared.SourceSpan);
    }
}
