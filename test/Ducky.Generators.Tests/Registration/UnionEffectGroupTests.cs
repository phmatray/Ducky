using Ducky.Generators.Tests.Infrastructure;
using Microsoft.CodeAnalysis;

namespace Ducky.Generators.Tests.Registration;

// ADR-0051 (#314): a partial EffectGroup<TAction> over a union gets a RegisterCases override with one On<Case> per case,
// read by the same case reader as union slices; a non-union action type is DUCKY026, a non-partial group DUCKY027, and
// DUCKY029-031 are shared with union slices (#324).
public sealed class UnionEffectGroupTests
{
    private const string Cart = """
        #pragma warning disable CS1591 // justification: undocumented test sources
        namespace App;
        public sealed record AddItem(int Count);
        public sealed record RemoveItem(int Count);
        public sealed record Clear;
        public sealed record Other;
        public union Inner(RemoveItem, Clear);
        public union CartAction(AddItem, Inner);

        """;

    private const string Handle = """
            public override System.Threading.Tasks.Task Handle(CartAction action, Ducky.EffectContext context, System.Threading.CancellationToken cancellationToken) =>
                System.Threading.Tasks.Task.CompletedTask;
        """;

    // A good test here fails if a case gets no registration: the nested union's cases are registered through both wrappers.
    [Fact]
    public void UnionEffectGroup_RegistersEachCase_AndCompilesClean()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            public sealed partial class CartEffects : Ducky.EffectGroup<CartAction>
            {
            {{Handle}}
            }
            """), out var output);

        output.ShouldCompileClean();
        Generated(output, "App.CartEffects.UnionEffectGroup.g.cs").ShouldBe("""
            // <auto-generated/>
            #nullable enable

            namespace App;

            partial class CartEffects
            {
                /// <inheritdoc />
                protected override void RegisterCases()
                {
                    #pragma warning disable CS0612, CS0618 // justification: generated code references user [Obsolete] cases (GEN-06)
                    On<global::App.AddItem>((a, c, t) => Handle(new global::App.CartAction(a), c, t));
                    On<global::App.RemoveItem>((a, c, t) => Handle(new global::App.CartAction(new global::App.Inner(a)), c, t));
                    On<global::App.Clear>((a, c, t) => Handle(new global::App.CartAction(new global::App.Inner(a)), c, t));
                    #pragma warning restore CS0612, CS0618
                }
            }

            """, StringCompareShould.IgnoreLineEndings);
    }

    // An open action type is skipped, neither generated nor reported.
    [Fact]
    public void UnionEffectGroup_OpenActionType_IsSkipped()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + """
            public abstract partial class Shared<TAction> : Ducky.EffectGroup<TAction>
                where TAction : notnull;
            """), out var output);

        output.ShouldCompileClean();
        output.SyntaxTrees.ShouldNotContain(t => t.FilePath.EndsWith(".UnionEffectGroup.g.cs", StringComparison.Ordinal));
    }

    [Fact]
    public void UnionEffectGroup_NonUnionAction_IsDucky026()
    {
        var diagnostic = Diagnose(Cart + """
            public sealed partial class CartEffects : Ducky.EffectGroup<Other>
            {
                public override System.Threading.Tasks.Task Handle(Other action, Ducky.EffectContext context, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.CompletedTask;
            }
            """);

        diagnostic.Id.ShouldBe("DUCKY026");
        diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture)
            .ShouldBe("'App.CartEffects' derives from EffectGroup<TAction>, but its action type 'App.Other' is not a C# union");
    }

    [Fact]
    public void UnionEffectGroup_NotPartial_IsDucky027()
    {
        var diagnostic = Diagnose(Cart + $$"""
            public sealed class CartEffects : Ducky.EffectGroup<CartAction>
            {
            {{Handle}}
            }
            """);

        diagnostic.Id.ShouldBe("DUCKY027");
        diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture).ShouldBe("The cases of 'App.CartEffects' can't be registered: declare 'App.CartEffects' partial");
    }

    // #324: a union effect group gets the union slices' DUCKY029, DUCKY030 and DUCKY031, not ids of its own.
    [Theory]
    [InlineData("public interface IItem; public union Bad(AddItem, IItem);", "public sealed partial class CartEffects : Ducky.EffectGroup<Bad>", "Bad", "", "DUCKY029")]
    [InlineData("public union Bad(AddItem, int?);", "public sealed partial class CartEffects : Ducky.EffectGroup<Bad>", "Bad", "", "DUCKY029")]
    [InlineData("", "file sealed partial class CartEffects : Ducky.EffectGroup<CartAction>", "CartAction", "", "DUCKY030")]
    [InlineData("", "public sealed partial class CartEffects : Ducky.EffectGroup<CartAction>", "CartAction",
        "protected override void RegisterCases() { }", "DUCKY031")]
    public void UnionEffectGroup_SliceMistakes_ReportTheSliceIds(string union, string declaration, string action, string member, string id)
    {
        var diagnostic = Diagnose(Cart + union + $$"""

            {{declaration}}
            {
                public override System.Threading.Tasks.Task Handle({{action}} action, Ducky.EffectContext context, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.CompletedTask;
                {{member}}
            }
            """);

        diagnostic.Id.ShouldBe(id);
    }

    // One diagnostic, no override emitted, and the output still compiles (the group merely registers nothing).
    private static Diagnostic Diagnose(string source)
    {
        DiagnosingHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(source), out var output, out var diagnostics);
        output.ShouldCompileClean();
        output.SyntaxTrees.ShouldNotContain(t => t.FilePath.EndsWith(".UnionEffectGroup.g.cs", StringComparison.Ordinal));
        return diagnostics.ShouldHaveSingleItem();
    }

    private static string Generated(Compilation output, string hintName) =>
        output.SyntaxTrees.Single(t => t.FilePath.EndsWith(hintName, StringComparison.Ordinal)).ToString();
}
