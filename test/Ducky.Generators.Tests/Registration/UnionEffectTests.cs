using Ducky.Generators.Tests.Infrastructure;
using Microsoft.CodeAnalysis;

namespace Ducky.Generators.Tests.Registration;

// #345: Effect<TUnion> gets its cases registered, and Effect<NonUnion>, the ordinary effect, stays out of the union rules.
public sealed class UnionEffectTests
{
    private const string Cart = """
        #pragma warning disable CS1591 // justification: undocumented test sources
        namespace App;
        public sealed record AddItem(int Count);
        public sealed record RemoveItem(int Count);
        public sealed record Clear;
        public sealed record Other;
        public union Inner(RemoveItem, Clear);
        public union CartAction(AddItem, Inner);

        """;

    private const string Handle = """
            public override System.Threading.Tasks.Task Handle(CartAction action, Ducky.EffectContext context, System.Threading.CancellationToken cancellationToken) =>
                System.Threading.Tasks.Task.CompletedTask;
        """;

    // A good test here fails if a case gets no registration: the nested union's cases are registered through both wrappers.
    [Fact]
    public void UnionEffect_RegistersEachCase_AndCompilesClean()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            public sealed partial class CartEffect : Ducky.Effect<CartAction>
            {
            {{Handle}}
            }
            """), out var output);

        output.ShouldCompileClean();
        Generated(output, "App.CartEffect.UnionEffect.g.cs").ShouldBe("""
            // <auto-generated/>
            #nullable enable

            namespace App;

            partial class CartEffect
            {
                /// <inheritdoc />
                protected override void RegisterCases()
                {
                    #pragma warning disable CS0612, CS0618 // justification: generated code references user [Obsolete] cases (GEN-06)
                    OnCase<global::App.AddItem>(a => new global::App.CartAction(a));
                    OnCase<global::App.RemoveItem>(a => new global::App.CartAction(new global::App.Inner(a)));
                    OnCase<global::App.Clear>(a => new global::App.CartAction(new global::App.Inner(a)));
                    #pragma warning restore CS0612, CS0618
                }
            }

            """, StringCompareShould.IgnoreLineEndings);
    }

    // The union stays the type Handle switches over, so the compiler still checks that every case is handled. The
    // exhaustive switch is the control: it shows that the missing arm alone causes the warning.
    [Theory]
    [InlineData("AddItem => System.Threading.Tasks.Task.CompletedTask,", "CS8509")]
    [InlineData("AddItem or Inner => System.Threading.Tasks.Task.CompletedTask,", null)]
    public void UnionEffect_MissingCaseInSwitch_IsCs8509(string arms, string? expected)
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            public sealed partial class CartEffect : Ducky.Effect<CartAction>
            {
                public override System.Threading.Tasks.Task Handle(CartAction action, Ducky.EffectContext context, System.Threading.CancellationToken cancellationToken) =>
                    action switch
                    {
                        {{arms}}
                    };
            }
            """), out var output);

        output.SyntaxTrees.ShouldContain(t => t.FilePath.EndsWith(".UnionEffect.g.cs", StringComparison.Ordinal));
        output.GetDiagnostics(TestContext.Current.CancellationToken)
            .Where(d => d.Severity != DiagnosticSeverity.Hidden)
            .Select(d => d.Id)
            .ShouldBe(expected is null ? [] : [expected]);
    }

    // Effect<NonUnion> is the ordinary effect: no union rule applies to it, whatever its shape. A file-local one keeps the
    // DUCKY023 of every file-local effect (SPEC §16.1), which says it isn't registered; DUCKY030 would replace it.
    [Theory]
    [InlineData("public sealed partial class PlainEffect", null)]
    [InlineData("public sealed class PlainEffect", null)]
    [InlineData("file sealed class PlainEffect", "DUCKY023")]
    public void PlainEffect_IsNotGeneratedNorReported(string declaration, string? registration)
    {
        DiagnosingHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + $$"""
            {{declaration}} : Ducky.Effect<Other>
            {
                public override System.Threading.Tasks.Task Handle(Other action, Ducky.EffectContext context, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.CompletedTask;
            }
            """), out var output, out var diagnostics);

        output.ShouldCompileClean();
        output.SyntaxTrees.ShouldNotContain(t => t.FilePath.EndsWith(".UnionEffect.g.cs", StringComparison.Ordinal));
        diagnostics.Select(d => d.Id).ShouldBe(registration is null ? [] : [registration]);
    }

    // An open action type is skipped, neither generated nor reported.
    [Fact]
    public void UnionEffect_OpenActionType_IsSkipped()
    {
        GeneratorHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(Cart + """
            public abstract partial class Shared<TAction> : Ducky.Effect<TAction>
                where TAction : notnull;
            """), out var output);

        output.ShouldCompileClean();
        output.SyntaxTrees.ShouldNotContain(t => t.FilePath.EndsWith(".UnionEffect.g.cs", StringComparison.Ordinal));
    }

    [Fact]
    public void UnionEffect_NotPartial_IsDucky027()
    {
        var diagnostic = Diagnose(Cart + $$"""
            public sealed class CartEffect : Ducky.Effect<CartAction>
            {
            {{Handle}}
            }
            """);

        diagnostic.Id.ShouldBe("DUCKY027");
        diagnostic.GetMessage(System.Globalization.CultureInfo.InvariantCulture).ShouldBe("The cases of 'App.CartEffect' can't be registered: declare 'App.CartEffect' partial");
    }

    // A union effect gets the ids of the other union-first types, not ids of its own.
    [Theory]
    [InlineData("public interface IItem; public union Bad(AddItem, IItem);", "public sealed partial class CartEffect : Ducky.Effect<Bad>", "Bad", "", "DUCKY029")]
    [InlineData("public union Bad(AddItem, int?);", "public sealed partial class CartEffect : Ducky.Effect<Bad>", "Bad", "", "DUCKY029")]
    [InlineData("", "file sealed partial class CartEffect : Ducky.Effect<CartAction>", "CartAction", "", "DUCKY030")]
    [InlineData("", "public sealed partial class CartEffect : Ducky.Effect<CartAction>", "CartAction",
        "protected override void RegisterCases() { }", "DUCKY031")]
    [InlineData("[System.Obsolete(\"gone\", true)] public sealed record Gone; [System.Obsolete] public union Bad(AddItem, Gone);",
        "#pragma warning disable CS0612\npublic sealed partial class CartEffect : Ducky.Effect<Bad>", "Bad", "", "DUCKY032")]
    public void UnionEffect_SliceMistakes_ReportTheSliceIds(string union, string declaration, string action, string member, string id)
    {
        var diagnostic = Diagnose(Cart + union + $$"""

            {{declaration}}
            {
                public override System.Threading.Tasks.Task Handle({{action}} action, Ducky.EffectContext context, System.Threading.CancellationToken cancellationToken) =>
                    System.Threading.Tasks.Task.CompletedTask;
                {{member}}
            }
            """);

        diagnostic.Id.ShouldBe(id);
        diagnostic.Location.SourceTree.ShouldNotBeNull().ToString().Substring(diagnostic.Location.SourceSpan.Start, diagnostic.Location.SourceSpan.Length).ShouldBe("CartEffect");
    }

    // One diagnostic, no override emitted, and the output still compiles (the effect merely registers no case).
    private static Diagnostic Diagnose(string source)
    {
        DiagnosingHarness.Run(new RegistrationGenerator(), GeneratorHarness.Compile(source), out var output, out var diagnostics);
        output.ShouldCompileClean();
        output.SyntaxTrees.ShouldNotContain(t => t.FilePath.EndsWith(".UnionEffect.g.cs", StringComparison.Ordinal));
        return diagnostics.ShouldHaveSingleItem();
    }

    private static string Generated(Compilation output, string hintName) =>
        output.SyntaxTrees.Single(t => t.FilePath.EndsWith(hintName, StringComparison.Ordinal)).ToString();
}
