using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using VerifyTests;
using VerifyXunit;

namespace Ducky.Generators.Tests.Infrastructure;

// GEN-06 test infrastructure (SPEC §16.1): consumer compilations over the real Ducky.dll, never stubs, under the strictest
// consumer settings, the generator driver with step tracking, Verify snapshots and the per-step caching check.
internal static class GeneratorHarness
{
    public static readonly CSharpParseOptions ParseOptions = new(LanguageVersion.Latest, DocumentationMode.Diagnose);

    private static readonly CSharpCompilationOptions _compilationOptions = new(
        OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable, warningLevel: 9999);

    // The running framework, plus the real Ducky.dll and the packages it references.
    private static readonly ImmutableArray<MetadataReference> _references = LoadReferences();

    private static ImmutableArray<MetadataReference> LoadReferences()
    {
        var ducky = typeof(DuckyActionAttribute).Assembly;
        var names = ducky.GetReferencedAssemblies().Select(a => a.Name).Append(ducky.GetName().Name).ToHashSet();
        var framework = Path.GetDirectoryName(typeof(object).Assembly.Location);
        return [.. ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
            .Where(p => Path.GetDirectoryName(p) == framework || names.Contains(Path.GetFileNameWithoutExtension(p)))
            .Select(p => MetadataReference.CreateFromFile(p))];
    }

    public static CSharpCompilation Compile(params string[] sources) => CSharpCompilation.Create(
        "Consumer", sources.Select(s => CSharpSyntaxTree.ParseText(s, ParseOptions)), _references, _compilationOptions);

    // A generator exception (CS8785) drops that generator's output from `output`, and a diagnostic it reports never
    // reaches `output`: both fail here, or ShouldCompileClean would pass over a crashing shape (INV-25).
    public static GeneratorDriver Run(IIncrementalGenerator generator, Compilation compilation, out Compilation output)
    {
        var driver = CSharpGeneratorDriver.Create(
                [generator.AsSourceGenerator()],
                parseOptions: ParseOptions,
                driverOptions: new GeneratorDriverOptions(IncrementalGeneratorOutputKind.None, trackIncrementalGeneratorSteps: true))
            .RunGeneratorsAndUpdateCompilation(compilation, out output, out var diagnostics, TestContext.Current.CancellationToken);
        driver.GetRunResult().Results.Select(r => r.Exception?.ToString()).OfType<string>().ShouldBeEmpty();
        diagnostics.Where(d => d.Severity != DiagnosticSeverity.Hidden).Select(d => d.ToString()).ShouldBeEmpty();
        return driver;
    }

    // Any diagnostic but a hidden one fails (GEN-06).
    public static void ShouldCompileClean(this Compilation compilation) =>
        compilation.GetDiagnostics(TestContext.Current.CancellationToken)
            .Where(d => d.Severity != DiagnosticSeverity.Hidden)
            .Select(d => d.ToString())
            .ShouldBeEmpty();

    // Generated sources are snapshotted as .txt: a committed .cs headed `// <auto-generated/>` fails ExclusionGate (§17.1).
    public static SettingsTask VerifyRun(GeneratorDriver driver)
    {
        var run = driver.GetRunResult();
        return Verifier.Verify(
            new { run.Diagnostics },
            run.Results.SelectMany(r => r.GeneratedSources)
                .OrderBy(s => s.HintName, StringComparer.Ordinal)
                .Select(s => new Target("txt", s.SourceText.ToString(), s.HintName)));
    }

    // Caching_{Step}_Cached: after an unrelated edit, every output of each named step is Cached or Unchanged. A model
    // holding a symbol or a compilation compares unequal across compilations, so it fails here too.
    public static void ShouldCacheSteps(IIncrementalGenerator generator, Compilation compilation, params string[] trackingNames)
    {
        var driver = Run(generator, compilation, out _);
        var edited = compilation.AddSyntaxTrees(CSharpSyntaxTree.ParseText("internal static class UnrelatedEdit { }", ParseOptions));
        var steps = driver.RunGenerators(edited, TestContext.Current.CancellationToken).GetRunResult().Results.Single().TrackedSteps;
        foreach (var name in trackingNames)
        {
            steps.ShouldContainKey(name); // Roslyn records no key for a step that never produced an output.
            var outputs = steps[name].SelectMany(s => s.Outputs).Select(o => o.Reason).ToList();
            outputs.ShouldAllBe(r => r == IncrementalStepRunReason.Cached || r == IncrementalStepRunReason.Unchanged, name);
        }
    }
}
