    // Fallout writes this header line into every file it generates; hand-written workflows (pr-title.yml) lack it.
    private const string GeneratedMarker = "# <auto-generated>";

    private static readonly Regex PlaywrightVersion = new("<PackageVersion Include=\"Microsoft.Playwright\" Version=\"([^\"]+)\"");

    // A C# fence (```csharp, ```cs, ~~~c#, any case) at any indent, also inside list items and blockquotes (CommonMark
    // containers). It would also flag an indented code block that shows a literal C# fence; no user doc needs one.
    private static readonly Regex CSharpFence = new(@"^[ \t>]*(?:(?:[-*+]|\d+[.)])[ \t]+)*(`{3,}|~{3,})[ \t]*(csharp|cs|c#)(?![\w#+-])",
        RegexOptions.Multiline | RegexOptions.IgnoreCase);

    // The copied design record, not user docs (§17.1).
    private static readonly string[] FenceExemptDocs = ["docs/spec/", "docs/adr/"];

    private AbsolutePath Workflows => RootDirectory / ".github" / "workflows";

    private Target VerifyWorkflows => _ => _
        .Executes(() =>
        {
            var generated = Artifacts / "workflows";
            generated.CreateOrCleanDirectory();
            var environment = new Dictionary<string, string>(EnvironmentInfo.Variables)
            {
                [DuckyGitHubActionsAttribute.OutputDirectoryVariable] = generated,
            };
            foreach (var workflow in typeof(Build).GetCustomAttributes<DuckyGitHubActionsAttribute>())
            {
                ProcessTasks.StartProcess(BuildAssemblyFile, $"--generate-configuration {workflow.Id} --host GitHubActions",
                    workingDirectory: RootDirectory, environmentVariables: environment, logOutput: false).AssertZeroExitCode();
            }

            var violations = WorkflowViolations(ReadYaml(generated), ReadYaml(Workflows))
                .Concat(WorkflowSelfCheck())
                .ToList();
            violations.ForEach(v => Log.Error(v));
            Assert.True(violations.Count == 0,
                $"VerifyWorkflows: {violations.Count} violation(s); the regenerated files are in {RootDirectory.GetRelativePathTo(generated)}");
        });

    // v0 (M0-11): the fence check only; the migration samples, the diagnostics pages and docfx join with their stories.
    private Target Docs => _ => _
        .DependsOn(Compile)
        .Executes(() =>
        {
            var docs = (RootDirectory / "docs").GlobFiles("**/*.md")
                .Select(f => (Path: RootDirectory.GetUnixRelativePathTo(f).ToString(), Text: f.ReadAllText()));
            var violations = DocsFenceViolations(docs).Concat(DocsSelfCheck()).ToList();
            violations.ForEach(v => Log.Error(v));
            Assert.True(violations.Count == 0, $"Docs: {violations.Count} violation(s)");
        });

    public void ConfigureSteps(GitHubActionsStepPipeline pipeline)
    {
        switch (pipeline.WorkflowName)
        {
            case "aot":
                // The workload must land in the SDK of global.json, which Fallout's run step sets up only after PreRun.
                pipeline.Insert(GitHubActionsStepPosition.PreRun, [
                    new GitHubActionsCustomStep
                    {
                        Name = "Setup: .NET SDK for the workload",
                        Uses = pipeline.BuiltInSteps.OfType<GitHubActionsRunStep>().Single().SetupDotNetAction,
                        With = { ["global-json-file"] = "global.json" },
                    },
                    new GitHubActionsCustomStep { Name = "Install: wasm-tools", Run = ["dotnet workload install wasm-tools"] },
                ]);
                break;
            case "e2e":
                // The npm CLI of the Microsoft.Playwright pin (the two share version numbers; Renovate bumps both).
                var pin = PlaywrightVersion.Match((RootDirectory / "Directory.Packages.props").ReadAllText());
                Assert.True(pin.Success, "Directory.Packages.props: no <PackageVersion Include=\"Microsoft.Playwright\" Version=\"...\"> for the e2e workflow");
                var playwright = pin.Groups[1].Value;
                pipeline.Insert(GitHubActionsStepPosition.PreRun, new GitHubActionsCustomStep
                {
                    Name = "Install: Playwright dependencies",
                    Run = [$"npx --yes playwright@{playwright} install-deps chromium"],
                });
                break;
        }

        if (pipeline.WorkflowName.StartsWith("nightly-", StringComparison.Ordinal))
        {
            pipeline.Insert(GitHubActionsStepPosition.JobEnd, new GitHubActionsCustomStep
            {
                Name = "Report: nightly failure",
                // A timeout-minutes overrun cancels the job, and failure() skips the step (scheduled runs have no concurrency cancel).
                If = "failure() || cancelled()",
                Env =
                {
                    ["GH_TOKEN"] = "${{ github.token }}",
                    ["GH_REPO"] = "${{ github.repository }}",
                    ["TITLE"] = $"{pipeline.WorkflowName} failed",
                    ["RUN_URL"] = "${{ github.server_url }}/${{ github.repository }}/actions/runs/${{ github.run_id }}",
                },
                Run =
                [
                    "number=$(gh issue list --state open --search \"$TITLE in:title\" --json number,title --jq 'map(select(.title == env.TITLE)) | first | .number // empty')",
                    "if [ -n \"$number\" ]; then",
                    "  gh issue comment \"$number\" --body \"Failed again: $RUN_URL\"",
                    "else",
                    "  gh issue create --title \"$TITLE\" --body \"The scheduled run failed: $RUN_URL\"",
                    "fi",
                ],
            });
        }
    }

    private static Dictionary<string, string> ReadYaml(AbsolutePath directory) =>
        directory.GlobFiles("*.yml", "*.yaml").ToDictionary(f => f.Name, f => f.ReadAllText());

    // generated: the files the attributes produce; committed: every file of .github/workflows. The committed copy of a
    // generated file must be identical, a committed generated file must still have an attribute, every generated job is
    // named after its workflow (S-8), and job names are unique across all workflows (the required checks of §20.2).
    private static IEnumerable<string> WorkflowViolations(Dictionary<string, string> generated, Dictionary<string, string> committed)
    {
        foreach (var (file, text) in generated.OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            if (!committed.TryGetValue(file, out var committedText))
            {
                yield return $"{file}: generated but not committed to .github/workflows";
            }
            else if (committedText.ReplaceLineEndings("\n") != text.ReplaceLineEndings("\n"))
            {
                yield return $"{file}: differs from the generated workflow (hand edit, or Build.CI.cs changed without regenerating)";
            }

            foreach (var (key, name) in Jobs(text).Where(j => j.Name != Path.GetFileNameWithoutExtension(file)))
            {
                yield return $"{file}: job '{key}' is named '{name}', not after its workflow '{Path.GetFileNameWithoutExtension(file)}' (S-8)";
            }
        }

        foreach (var file in committed.Where(c => c.Value.Contains(GeneratedMarker, StringComparison.Ordinal) && !generated.ContainsKey(c.Key))
                     .Select(c => c.Key).Order(StringComparer.Ordinal))
        {
            yield return $"{file}: generated by Fallout, but no attribute generates it any more";
        }

        var jobs = new List<(string File, string Name)>();
        var invalid = new List<string>();
        foreach (var (file, text) in committed.OrderBy(c => c.Key, StringComparer.Ordinal))
        {
            try
            {
                jobs.AddRange(Jobs(text).Select(j => (file, j.Name)));
            }
            catch (YamlException e)
            {
                invalid.Add($"{file}: not valid YAML: {e.Message}");
            }
        }

        foreach (var violation in invalid)
        {
            yield return violation;
        }

        foreach (var shared in jobs.GroupBy(j => j.Name).Where(g => g.Count() > 1))
        {
            yield return $"job name '{shared.Key}' is not unique: {string.Join(", ", shared.Select(j => j.File))}";
        }
    }

    // Each job's key and the name GitHub reports for it (its name:, else its key).
    private static List<(string Key, string Name)> Jobs(string workflow)
    {
        var stream = new YamlStream();
        stream.Load(new StringReader(workflow));
        if (stream.Documents.FirstOrDefault()?.RootNode is not YamlMappingNode root ||
            !root.Children.TryGetValue("jobs", out var jobsNode) || jobsNode is not YamlMappingNode jobs)
        {
            return [];
        }

        return [.. jobs.Children.Select(job => (
            Key: ((YamlScalarNode)job.Key).Value!,
            Name: job.Value is YamlMappingNode body && body.Children.TryGetValue("name", out var name) ? ((YamlScalarNode)name).Value! : ((YamlScalarNode)job.Key).Value!))];
    }

    // Every snippet is a #region of a compiled, tested file (§17.1).
    private static IEnumerable<string> DocsFenceViolations(IEnumerable<(string Path, string Text)> docs) =>
        docs.Where(d => !FenceExemptDocs.Any(e => d.Path.StartsWith(e, StringComparison.Ordinal)))
            .SelectMany(d => CSharpFence.Matches(d.Text).Select(m =>
                $"{d.Path}:{d.Text.AsSpan(0, m.Index).Count('\n') + 1}: fenced C# block; include a #region of a compiled, tested file instead"));

    // The acceptance checks of M0-11, planted on miniature workflows.
    private static IEnumerable<string> WorkflowSelfCheck()
    {
        static string Workflow(string name, string jobKey, string jobName, bool generatedFile = true) =>
            (generatedFile ? $"{GeneratedMarker}\n" : "") + $"name: {name}\non: [push]\njobs:\n  {jobKey}:\n    name: {jobName}\n    runs-on: ubuntu-latest\n";
        Dictionary<string, string> Generated() => new()
        {
            ["ci.yml"] = Workflow("ci", "ci", "ci"),
            ["aot.yml"] = Workflow("aot", "aot", "aot"),
        };
        Dictionary<string, string> Committed(Action<Dictionary<string, string>>? plant = null)
        {
            var committed = new Dictionary<string, string>(Generated()) { ["pr-title.yml"] = Workflow("pr-title", "pr-title", "pr-title", generatedFile: false) };
            plant?.Invoke(committed);
            return committed;
        }
        static Dictionary<string, string> Fallout(Dictionary<string, string> workflows) =>
            workflows.ToDictionary(w => w.Key, w => w.Value.Replace($"    name: {Path.GetFileNameWithoutExtension(w.Key)}\n", "    name: ubuntu-latest\n", StringComparison.Ordinal));
        (string Case, List<string> Violations, string Expected)[] planted =
        [
            ("a hand edit to ci.yml", [.. WorkflowViolations(Generated(), Committed(c => c["ci.yml"] += "    timeout-minutes: 5\n"))],
                "ci.yml: differs from the generated workflow"),
            ("a generated workflow left uncommitted", [.. WorkflowViolations(Generated(), Committed(c => c.Remove("aot.yml")))],
                "aot.yml: generated but not committed"),
            ("a generated workflow whose attribute is gone", [.. WorkflowViolations(Generated(), Committed(c => c["old.yml"] = Workflow("old", "old", "old")))],
                "old.yml: generated by Fallout, but no attribute generates it"),
            ("a hand-written workflow reusing the job name ci", [.. WorkflowViolations(Generated(), Committed(c => c["pr-title.yml"] = Workflow("pr-title", "pr-title", "ci", generatedFile: false)))],
                "job name 'ci' is not unique: ci.yml, pr-title.yml"),
            ("Fallout's default job name (S-8)", [.. WorkflowViolations(Fallout(Generated()), Fallout(Committed()))],
                "ci.yml: job 'ci' is named 'ubuntu-latest', not after its workflow 'ci' (S-8)"),
            ("Fallout's default job names, shared by two workflows", [.. WorkflowViolations(Fallout(Generated()), Fallout(Committed()))],
                "job name 'ubuntu-latest' is not unique: aot.yml, ci.yml"),
            ("a committed workflow that is not YAML", [.. WorkflowViolations(Generated(), Committed(c => c["broken.yml"] = "jobs: [\n"))],
                "broken.yml: not valid YAML"),
        ];
        foreach (var violation in WorkflowViolations(Generated(), Committed()))
        {
            yield return $"WorkflowSelfCheck: the unplanted workflows must pass, got: {violation}";
        }
        foreach (var violation in WorkflowViolations(Generated(), Committed(c => c["ci.yml"] = c["ci.yml"].ReplaceLineEndings("\r\n"))))
        {
            yield return $"WorkflowSelfCheck: a CRLF checkout of ci.yml must pass, got: {violation}";
        }
        foreach (var (plantedCase, violations, expected) in planted.Where(p => !p.Violations.Any(v => v.Contains(p.Expected, StringComparison.Ordinal))))
        {
            yield return $"WorkflowSelfCheck: {plantedCase} must report '{expected}', got [{string.Join("; ", violations)}]";
        }
    }

    // The acceptance check of M0-11, planted on miniature docs.
    private static IEnumerable<string> DocsSelfCheck()
    {
        const string fenced = "# Guide\n\n```csharp\nvar store = new Store();\n```\n";
        (string Path, string Text)[] unplanted =
        [
            ("docs/spec/SPEC.md", fenced),
            ("docs/adr/0001-record.md", fenced),
            ("docs/guides/selectors.md", "```json\n{}\n```\n\n[!code-csharp[](../../test/Ducky.Docs.Tests/Guide.cs#select)]\n"),
        ];
        (string Path, string Text, string Expected)[] planted =
        [
            ("docs/guides/getting-started.md", fenced, "docs/guides/getting-started.md:3: fenced C# block"),
            ("docs/guides/indented.md", "text\n\n   ```CSharp\n", "docs/guides/indented.md:3: fenced C# block"),
            ("docs/guides/short.md", "~~~cs\n~~~\n", "docs/guides/short.md:1: fenced C# block"),
            ("docs/guides/sharp.md", "```c# title=x\n```\n", "docs/guides/sharp.md:1: fenced C# block"),
            ("docs/specification/x.md", fenced, "docs/specification/x.md:3: fenced C# block"),
            ("docs/guides/list.md", "1. Install:\n\n    ```csharp\n    ```\n", "docs/guides/list.md:3: fenced C# block"),
            ("docs/guides/nested.md", "- a\n  - b\n\n      ```cs\n      ```\n", "docs/guides/nested.md:4: fenced C# block"),
            ("docs/guides/marker.md", "1. ```csharp\n   ```\n", "docs/guides/marker.md:1: fenced C# block"),
            ("docs/guides/quote.md", "> ```csharp\n> ```\n", "docs/guides/quote.md:1: fenced C# block"),
            ("docs/guides/tab.md", "- a\n\n\t```csharp\n\t```\n", "docs/guides/tab.md:3: fenced C# block"),
        ];
        foreach (var violation in DocsFenceViolations(unplanted))
        {
            yield return $"DocsSelfCheck: the unplanted docs must pass, got: {violation}";
        }
        foreach (var (path, text, expected) in planted)
        {
            var violations = DocsFenceViolations([(path, text)]).ToList();
            if (!violations.Any(v => v.Contains(expected, StringComparison.Ordinal)))
            {
                yield return $"DocsSelfCheck: a fenced block in {path} must report '{expected}', got [{string.Join("; ", violations)}]";
            }
        }
    }
